import { test, expect } from '@playwright/test'
import { installGradingFixture } from './grading-fixture.mjs'

const base = '/courses/1/exams/midterm-2'
const grade = `${base}/grade?q=Q2&student=111`

test('course → exam → question → student → Submission uses the original compact grading UI', async ({ page }) => {
  const state = await installGradingFixture(page)
  await page.goto('/courses')
  await page.getByRole('button', { name: /TA Course options CMSC250/ }).click()
  await page.getByRole('link', { name: /Midterm 2/ }).click()
  await expect(page).toHaveURL(`${base}/grading-queue`)
  await page.getByLabel('Question', { exact: true }).selectOption('Q2')
  await expect(page.getByRole('link', { name: 'View students', exact: true })).toHaveCount(1)
  await page.getByRole('link', { name: 'View students', exact: true }).click()
  await expect(page).toHaveURL(new RegExp('/grading-queue/Q2/students$'))
  await expect(page.getByRole('link', { name: 'No Scan', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Alice Adams', exact: true }).click()
  await expect(page).toHaveURL(grade)
  await expect(page.getByRole('heading', { name: 'Q2 · Functions', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Q1 · Logic', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Q3 · Proof', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Submission', exact: true })).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Next student', exact: true })).toHaveCount(0)
  await expect(page.getByRole('search', { name: 'Filter exams' })).toHaveCount(0)
  const rubric = page.getByRole('complementary', { name: 'Question rubric' })
  await expect(rubric).toHaveCSS('width', '480px')
  await expect(page.getByRole('heading', { name: 'Question rubric', exact: true })).toHaveCSS('font-size', '15px')
  await expect(page.getByRole('button', { name: 'Criterion', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Regrade', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Import rubric', exact: true })).toBeVisible()
  await expect(page.locator('canvas:visible').first()).toBeVisible()
  await expect(page.getByRole('region', { name: 'Student exam' }).getByText('Q2 · Functions', { exact: true })).toBeInViewport()
  const correct = page.getByRole('button', { name: /Correct Q2/ })
  await expect(correct).toHaveCSS('font-size', '11px')
  await correct.click()
  await expect(correct).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Comment to student', exact: true }).click()
  await page.getByLabel('Comment to student', { exact: true }).fill('Good reasoning')
  await page.getByRole('button', { name: 'Submission', exact: true }).click()
  await expect(page).toHaveURL(`${base}/grading-queue/Q2/students?submitted=111`)
  const row = page.getByRole('row').filter({ has: page.getByRole('link', { name: 'Alice Adams', exact: true }) })
  await expect(row).toContainText('Finished')
  await expect(row).toContainText('10 / 10')
  expect(state.decisions['111'].Q2.comment).toBe('Good reasoning')
  expect(state.mutations.filter((m) => m.path.endsWith('/decision')).every((m) => m.path.includes('/questions/Q2/'))).toBe(true)
  await page.reload()
  await expect(row).toContainText('Finished')
})

test('original add, edit, import and regrade controls still work for the selected question', async ({ page }) => {
  const state = await installGradingFixture(page)
  state.decisions['111'].Q2 = { criteria: ['201'], score: 10, version: 1, grader_directory_id: 'ta1' }
  await page.goto(grade)
  await page.getByRole('button', { name: 'Criterion', exact: true }).click()
  await page.getByLabel('Points', { exact: true }).fill('2')
  await page.getByLabel('Title · shown to students', { exact: true }).fill('Missing justification')
  await page.getByRole('button', { name: 'Save criterion', exact: true }).click()
  await expect(page.getByRole('button', { name: /Missing justification/ })).toBeVisible()
  await page.getByRole('button', { name: 'Not now', exact: true }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('button', { name: 'Edit Correct Q2', exact: true }).click()
  await page.getByLabel('Title · shown to students', { exact: true }).fill('Complete argument')
  await page.getByRole('button', { name: 'Save criterion', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit Complete argument', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Import rubric', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Import previous rubric' })).toBeVisible()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Regrade', exact: true }).click()
  await page.getByLabel('Why · graders see this in the queue', { exact: true }).fill('Check consistency')
  await page.getByRole('button', { name: 'Start regrade', exact: true }).click()
  await expect(page).toHaveURL(`${base}/regrade/review-1`)
  await expect(page.getByRole('heading', { name: 'Regrade · Check consistency', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Exit review', exact: true }).click()
  await expect(page).toHaveURL(`${base}/grading-queue/Q2/students`)
  await expect(page.getByRole('row').filter({ has: page.getByRole('link', { name: 'Alice Adams', exact: true }) })).toContainText('Need regrade')
  expect(state.mutations.find((m) => m.method === 'POST' && m.path.endsWith('/criteria')).body).toMatchObject({ title: 'Missing justification', deduction: -2 })
  expect(state.mutations.find((m) => m.method === 'PATCH' && m.path.endsWith('/201')).body.title).toBe('Complete argument')
  expect(state.mutations.find((m) => m.path.endsWith('/regrade-queues')).body.qid).toBe('Q2')
})

test('a failed Submission stays on the answer and surfaces the backend conflict', async ({ page }) => {
  const state = await installGradingFixture(page)
  await page.goto(grade)
  await page.getByRole('button', { name: /Correct Q2/ }).click()
  await expect.poll(() => state.decisions['111'].Q2?.version).toBe(1)
  state.failDecision = true
  await page.getByRole('button', { name: 'Submission', exact: true }).click()
  await expect(page.locator('main').getByRole('alert')).toContainText('This answer changed since you opened it')
  await expect(page).toHaveURL(grade)
  await expect(page.getByRole('button', { name: 'Submission', exact: true })).toBeEnabled()
})

test('another grader’s lock disables grading and incomplete entry links return to the queue', async ({ page }) => {
  const state = await installGradingFixture(page)
  state.locks = [{ qid: 'Q2', holder: 'ta2', holder_name: 'Another TA', mine: false }]
  await page.goto(grade)
  await expect(page.getByRole('button', { name: /Correct Q2/ })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Submission', exact: true })).toBeDisabled()
  await expect(page.getByText('Another TA is grading this answer')).toBeVisible()
  await page.goto(`${base}/grade?student=111`)
  await expect(page).toHaveURL(`${base}/grading-queue?student=111`)
  await page.goto(`${base}/grade?q=deleted&student=111`)
  await expect(page.getByRole('heading', { name: 'Choose a question to grade' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Submission', exact: true })).toHaveCount(0)
})

test('the queue and grading workspace fit a narrow viewport', async ({ page }) => {
  await installGradingFixture(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`${base}/grading-queue/Q2/students`)
  await expect(page.getByRole('link', { name: 'Alice Adams', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.getByRole('link', { name: 'Alice Adams', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Q2 · Functions', exact: true })).toBeVisible()
  await expect(page.locator('canvas:visible').first()).toBeVisible()
  expect((await page.getByRole('region', { name: 'Student exam' }).boundingBox()).height).toBeGreaterThan(400)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await expect(page.getByRole('button', { name: 'Submission', exact: true })).toHaveCount(1)
})
